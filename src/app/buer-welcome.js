export function pickWelcome(previous, random = Math.random) {
  const choices = WELCOME_LINES.map((_, i) => i).filter(i => i !== previous);
  return choices[Math.min(choices.length - 1, Math.max(0, Math.floor(random() * choices.length)))];
}
export function welcomeForVisit(storage, random = Math.random) {
  const key = 'buer-welcome-last-v1';
  let previous = -1;
  try { const value = storage?.getItem(key); if(value !== null && value !== undefined) previous = Number(value); } catch {}
  const index = pickWelcome(previous, random);
  try { storage?.setItem(key, String(index)); } catch {}
  return WELCOME_LINES[index];
}
